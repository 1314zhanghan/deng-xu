5. **无魔约束（本世界最重要的一条）**：**这个世界没有魔法，也没有任何超自然力量。** 一切被称为「神迹」的事，都必须能被解释成自然现象、误会、或者骗局。潮信摸得准，是因为那个老人记性好；星纪的星图有用，是因为星真的可以用来定位；底涌那几夜海会亮，是因为水里上浮的虾与磷光；有人在雾里听见钟声因而避开礁石，是因为对面船上真的有人在敲钟；礁民说「白水教的长老能预知天气」，其实是因为冰庙记了三百年的开渔日账，而账本比人聪明。**禁止**出现任何无法用自然解释的事件。如果情节里需要一个「神迹」，请务必在同一段里给出它的世俗解释——哪怕这个解释只有叙述者知道，而当事人至死相信那是神。

6. **航海是硬约束，出海不是随便就能出的**：任何一次出海都要写清四件事：**等什么风**（湿季风、燥季风、还是换风期不能走）、**带多少水**（一条二十人的船一天三桶，一桶约四十斤，二十天就是六十桶）、**船况如何**（船龄几年、上一次岁修是什么时候、缆换过没有）、**钱够不够撑到下一个补给点**。中途要靠港补水，而补水要排队、要付钱（一桶两文，旱季十文）。**坏血病必须作为一个真实威胁存在**：航程超过三十天就会有牙龈肿、旧伤裂开、走不动、说胡话。**风暴必须给征兆**（风的手印、海鸟一齐飞、空气突然变凉），并且**看见征兆就必须收帆或者砍桅**，砍桅是标准做法，不是英雄行为。**禁止**出现「顺风顺水就到了」「三天跨过半个洋」「船自己会找路」这类省略；如果跳过航程，必须交代这一段时间里死了谁、花了多少钱、坏了什么东西。

7. **武力有限，会受伤会死**：这个世界的人是会受伤、会感染、会残废、会死的。**以一敌三必败**，除非地形、装备、训练差距极大，而且即使赢了也要付出代价（受伤、暴露、结仇、丢东西）。船上打架比陆地上更凶，因为**在船上没有地方退**；一刀下去，血会把甲板弄滑，滑倒的人会掉海。受伤之后要写清后果：伤口怎么处理（烧灼、缝合、敷蜜）、几天不能用力、会不会发热、要不要截肢（截肢的死亡率大约一半）。**禁止**「一刀砍倒三个」「万军之中取上将首级」「身中数刀还站着」。任何一次动手都应该让主角更虚弱、更欠人、更惹麻烦，而不是更强。**这个世界的死亡处理得很实在**：尸体要裹、要沉、要报信；报信要花钱，而家属可能一个钱都拿不到。

8. **钱与信用的双重约束**：主角的每个决定背后都要有两笔账。第一笔是**钱**：住宿一晚两文到二十文、一顿饭五文到二十文、雇一个水手二百文、过礁的引水钱是三成货、岁修四两到八两——都要具体到文与两，并且写清他手上还剩多少、能撑几天。第二笔是**信**：他有没有欠着人、有没有替人做过保、有没有在契所留下过记录、有没有进过沙洲的死账。**在这个世界，「这个人说话算不算数」比「这个人有没有理」重要得多。** 主角不能随手赏人、不能一掷千金、不能让钱永远花不完；**也不能靠空口承诺办成大事**——他每说一句承诺，别人都会记住、引用、并在最不方便的时刻拿出来。反过来，信誉是可以攒的：按时还一笔小账、当着人面把欠的还清、在别人都跑的时候留下来，这些都算数。

